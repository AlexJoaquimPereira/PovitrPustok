#!/usr/bin/env python3
"""Generate values-b+kok+Latn/strings.xml from the Romi translation worksheet.

The CSV is the source of truth for translated strings. The generated locale is
complete: every default `<string>` is emitted, using the Romi cell when it is
filled and the English default otherwise, so a partial worksheet is
lint-clean and the fallback is explicit. Plurals are copied as English until
the worksheet gains plural rows.

Run this after editing the worksheet:

    python3 tools/translations/generate_romi_strings.py

The script fails on a stale key, a duplicate key, or a placeholder mismatch, so
a translation cannot silently lose a `%1$s` / `%1$d` argument.
"""
from __future__ import annotations

import csv
import re
import sys
import xml.etree.ElementTree as ET
from pathlib import Path
from xml.sax.saxutils import escape

ROOT = Path(__file__).resolve().parents[2]
BASE_STRINGS = ROOT / "app/src/main/res/values/strings.xml"
WORKSHEET = ROOT / "docs/translations/1.3.1-romi.csv"
OUTPUT = ROOT / "app/src/main/res/values-b+kok+Latn/strings.xml"
PLACEHOLDER = re.compile(r"%(?:\d+\$)?[sd]")
SUPPORTED_TAGS = {"string", "plurals"}


def flatten_text(element: ET.Element, label: str) -> str:
    """Text of a resource element, refusing nested markup the generator would drop."""
    if len(list(element)) != 0:
        raise SystemExit(
            f"{label} contains nested markup; the generator only handles plain text"
        )
    return "".join(element.itertext())


def base_resources() -> tuple[list[tuple[str, str]], list[tuple[str, list[tuple[str, str]]]]]:
    """Default strings and plurals, in source order, skipping non-translatable ones."""
    root = ET.parse(BASE_STRINGS).getroot()
    unsupported = sorted({element.tag for element in root} - SUPPORTED_TAGS)
    if unsupported:
        raise SystemExit(
            "values/strings.xml contains resource types the generator does not "
            f"copy: {unsupported}"
        )

    strings: list[tuple[str, str]] = []
    for element in root.findall("string"):
        if element.get("translatable") == "false":
            continue
        strings.append(
            (element.get("name"), flatten_text(element, f"string {element.get('name')}"))
        )

    plurals: list[tuple[str, list[tuple[str, str]]]] = []
    for element in root.findall("plurals"):
        if element.get("translatable") == "false":
            continue
        items = [
            (
                item.get("quantity"),
                flatten_text(item, f"plural {element.get('name')}/{item.get('quantity')}"),
            )
            for item in element.findall("item")
        ]
        plurals.append((element.get("name"), items))

    return strings, plurals


def android_escape(value: str) -> str:
    # The base strings already carry Android escapes such as `\'`; normalize
    # them before escaping so a generated resource never gets `\\'`.
    value = value.replace("\\'", "'").replace('\\"', '"')
    # XML first, then Android's own apostrophe/quote escaping. aapt rejects a
    # bare apostrophe in an unquoted string resource.
    value = escape(value)
    value = value.replace("'", "\\'").replace('"', '\\"')
    return value


def main() -> int:
    base, plurals = base_resources()
    base_by_name = dict(base)
    rows = list(csv.DictReader(WORKSHEET.open(encoding="utf-8-sig")))
    seen: set[str] = set()
    translated: dict[str, str] = {}

    for row in rows:
        if not any((row.get(column) or "").strip() for column in row):
            # A blank line from an editor is harmless; skip it.
            continue
        key = (row.get("key") or "").strip()
        romi = (row.get("romi") or "").strip()
        if not key:
            raise SystemExit("worksheet row without a key")
        if key in seen:
            raise SystemExit(f"duplicate worksheet key: {key}")
        seen.add(key)
        if key not in base_by_name:
            raise SystemExit(f"worksheet key is not in values/strings.xml: {key}")
        if not romi:
            continue
        english = base_by_name[key]
        if sorted(PLACEHOLDER.findall(english)) != sorted(PLACEHOLDER.findall(romi)):
            raise SystemExit(
                f"placeholder mismatch for {key}: "
                f"English {PLACEHOLDER.findall(english)} vs Romi {PLACEHOLDER.findall(romi)}"
            )
        translated[key] = romi

    untranslated = [key for key, _ in base if key not in translated]
    if untranslated:
        print(
            f"info: {len(untranslated)} default strings have no Romi value; "
            "the English text is emitted as the explicit fallback",
            file=sys.stderr,
        )

    OUTPUT.parent.mkdir(parents=True, exist_ok=True)
    lines = [
        '<?xml version="1.0" encoding="utf-8"?>',
        "<!-- Generated by tools/translations/generate_romi_strings.py from",
        "     docs/translations/1.3.1-romi.csv. Every default string is emitted;",
        "     an untranslated cell uses the English text as an explicit fallback.",
        "     Plurals are English until the worksheet supports them.",
        "     Do not edit by hand. -->",
        "<resources>",
    ]
    for key, english in base:
        lines.append(
            f'    <string name="{key}">{android_escape(translated.get(key, english))}</string>'
        )
    for name, items in plurals:
        lines.append(f'    <plurals name="{name}">')
        for quantity, text in items:
            lines.append(
                f'        <item quantity="{quantity}">{android_escape(text)}</item>'
            )
        lines.append("    </plurals>")
    lines.append("</resources>")
    lines.append("")
    OUTPUT.write_text("\n".join(lines), encoding="utf-8")
    print(
        f"wrote {OUTPUT.relative_to(ROOT)} with {len(base)} strings "
        f"({len(translated)} translated) and {len(plurals)} plurals"
    )
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
